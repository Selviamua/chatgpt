@dataclass
class Chapter:
    ordinal: int
    title: str
    body: str
    start: int
    end: int
    flags: list[str]

@dataclass
class Evidence:
    no: int
    chapter: str
    keyword: str
    category: str
    quote: str
    note: str
    grade: str = "【原文明确】"


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def parse(text: str) -> list[Chapter]:
    matches = list(HEADING.finditer(text))
    chapters: list[Chapter] = []
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        body = text[m.end():end]
        flags = [name for name, keys in TOPICS.items() if any(k.lower() in body.lower() for k in keys)]
        chapters.append(Chapter(i + 1, norm(m.group()), body, m.start(), end, flags))
    return chapters


def excerpt(chapters: list[Chapter], keyword: str, category: str, note: str,
            title_contains: str | None = None, before: int = 90, after: int = 230,
            grade: str = "【原文明确】") -> Evidence:
    key = keyword.lower()
    candidates = [c for c in chapters if title_contains is None or title_contains in c.title]
    for c in candidates:
        pos = c.body.lower().find(key)
        if pos >= 0:
            q = norm(c.body[max(0, pos-before): min(len(c.body), pos+len(keyword)+after)])
            return Evidence(0, c.title, keyword, category, q, note, grade)
        if key in c.title.lower():
            q = norm(c.body[: max(220, after)])
            return Evidence(0, c.title, keyword, category, q, note, grade)
    if title_contains is not None:
        return excerpt(chapters, keyword, category, note, None, before, after, grade)
    raise RuntimeError(f"keyword not found: {keyword!r} title={title_contains!r}")


