def build_evidence(chapters: list[Chapter]) -> list[Evidence]:
    items = []
    for spec in specs():
        e = excerpt(chapters, *spec)
        e.no = len(items) + 1
        items.append(e)
    return items


def ref(e: Evidence) -> str:
    return f"E{e.no:03d}"


def bykey(items: list[Evidence], keyword: str) -> Evidence:
    return next(e for e in items if e.keyword == keyword)


def quote_block(e: Evidence) -> str:
    return f"> **{ref(e)}｜{e.chapter}｜{e.grade}**：{e.quote}"


def evidence_bank(items: list[Evidence], chapter_count: int) -> str:
    lines = ["# 《科技入侵现代》证据摘录库", "", "## 使用说明", "",
             f"本库由脚本从原文的 **{chapter_count} 个章节标题块**中抽取。摘录按原文出现顺序保存，并保留章节来源。原始文本后半段存在较明显的错字、代词错置和疑似文本污染；摘录不擅自修复，以便复核。", "",
             "证据等级以【原文明确】为主；如果主文档给出跨段解释或现实对应，会另行标为【合理解释】或【延伸联想】。", ""]
    for e in sorted(items, key=lambda x: x.no):
        lines += [f"## {ref(e)}｜{e.chapter}", "", f"- **关键词**：{e.keyword}", f"- **分类**：{e.category}", f"- **证据等级**：{e.grade}", f"- **简短说明**：{e.note}", "", f"> {e.quote}", ""]
    return "\n".join(lines).rstrip() + "\n"


def inventory(chapters: list[Chapter]) -> str:
    out = ["## 附录 A：章节切分与主题初筛索引", "", "说明：这是按标题块自动切分的审计索引。`位置` 为原文字符偏移；`主要剧情线索` 采用章节标题，不等同于完整章节摘要。原文存在重复章号，因此增加顺序号。", "", "| 顺序号 | 章节标题 | 位置 | 主要剧情线索 | 主题标记 |", "|---:|---|---:|---|---|"]
    for c in chapters:
        flags = " / ".join(c.flags) if c.flags else "—"
        out.append(f"| {c.ordinal} | {c.title.replace('|','/')} | {c.start}–{c.end} | {c.title.replace('|','/')} | {flags} |")
    return "\n".join(out)


